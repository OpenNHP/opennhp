// RegistrationResult is the OTP and device-registration outcome shared by the
// iOS and Android SDK wrappers. It deliberately carries no private key: the
// result is serialized to JSON and handed to the platform layer, where it may
// be logged or captured in a crash report, so a secret must never travel in it.
// A key generated during the OTP request is delivered once, out of band, via
// TakeGeneratedKey.
type RegistrationResult struct {
	ErrCode       string `json:"errCode"`
	ErrMsg        string `json:"errMsg,omitempty"`
	PublicKey     string `json:"publicKey,omitempty"`
	AuthServiceId string `json:"aspId,omitempty"`
	ExpiresAt     *int64 `json:"expiresAt,omitempty"`
}

// generatedKeyHold carries a private key generated during an OTP request to the
// single TakeGeneratedKey call that the platform secure-store layer makes right
// after. It is a dedicated, out-of-band channel precisely so the key never
// enters RegistrationResult (and thus never a logged JSON blob). It is written
// on every RequestRegistrationOtp (cleared when nothing was generated) and
// zeroed the moment it is read, so at most one request's key is ever held.
var (
	generatedKeyMu   sync.Mutex
	generatedKeyHold string
)

// stashGeneratedKey records (or clears) the key awaiting TakeGeneratedKey.
func stashGeneratedKey(key string) {
	generatedKeyMu.Lock()
	generatedKeyHold = key
	generatedKeyMu.Unlock()
}

// TakeGeneratedKey returns the private key generated by the most recent
// RequestRegistrationOtp and clears it, so the secret is surrendered exactly
// once. It returns "" when the caller supplied the key or none was generated.
// The platform layer must call this immediately after a successful OTP request
// and write the result straight into secure storage: an uncollected key stays
// in process memory until the next RequestRegistrationOtp overwrites it.
func TakeGeneratedKey() string {
	generatedKeyMu.Lock()
	key := generatedKeyHold
	generatedKeyHold = ""
	generatedKeyMu.Unlock()
	return key
}

// JSON encodes the result. A marshal failure becomes a fixed error object.
func (r RegistrationResult) JSON() string {
	bytes, err := json.Marshal(r)
	if err != nil {
		return `{"errCode":"1","errMsg":"failed to encode registration result"}`
	}
	return string(bytes)
}

func registrationErrorCode(err error) string {
	type coder interface{ ErrorCode() string }
	if coded, ok := err.(coder); ok {
		if code := coded.ErrorCode(); code != "" {
			return code
		}
	}
	return "1"
}

func cipherSchemeFor(cipherType int) int {
	if core.EccTypeEnum(cipherType) == core.ECC_SM2 {
		return common.CIPHER_SCHEME_GMSM
	}
	return common.CIPHER_SCHEME_CURVE
}

// validRegistrationCipherType accepts only the two schemes the SDK documents:
// 0 = Curve25519, 1 = SM2. cipherSchemeFor maps everything else (ECC_UMI,
// garbage) to Curve silently, so callers reject the rest up front rather than
// register a device under a scheme the caller never asked for.
func validRegistrationCipherType(cipherType int) bool {
	return cipherType == int(core.ECC_CURVE25519) || cipherType == int(core.ECC_SM2)
}

// AgentHoldsRegistrationKey reports whether a's current device identity is the
// one that privateKeyBase64 + cipherType would produce. It compares derived
// PUBLIC keys, not the raw config string, so an agent started from a sealed
// on-disk key still matches the plaintext key the caller supplies, and the SDK
// init-with-key path can tell "already holds this key" from "holds a different
// key". Any uncertainty (nil agent/config, bad base64, unsupported key, scheme
// mismatch, or no device yet) returns false, which routes callers to the safe
// "close the agent first" path. The device is read only through the
// deviceMutex-guarded PublicKeyBase64ByCipherScheme (which returns "" when there
// is none), never directly here, so this stays race-free against a device swap.
func AgentHoldsRegistrationKey(a *UdpAgent, privateKeyBase64 string, cipherType int) bool {
	if a == nil || a.config == nil || privateKeyBase64 == "" {
		return false
	}
	if !validRegistrationCipherType(cipherType) {
		return false
	}
	if agentCipherScheme(a) != cipherSchemeFor(cipherType) {
		return false
	}
	priv, err := base64.StdEncoding.DecodeString(privateKeyBase64)
	if err != nil {
		return false
	}
	ecc := core.ECC_CURVE25519
	if core.EccTypeEnum(cipherType) == core.ECC_SM2 {
		ecc = core.ECC_SM2
	}
	e := core.ECDHFromKey(ecc, priv)
	if e == nil {
		return false
	}
	pub := e.PublicKeyBase64()
	return pub != "" && pub == a.PublicKeyBase64ByCipherScheme()
}

func configTomlExists(workingDir string) bool {
	_, err := os.Stat(filepath.Join(workingDir, "etc", "config.toml"))
	return err == nil
}

// StartAllowingMissingConfig starts an agent that may have no config.toml.
// A missing file makes loadBaseConfig apply the empty config's log level
// (silent) over the requested one, so the requested level is restored here
// through the agent's own logger. That keeps the fix inside the agent package
// instead of adding a setter to the shared nhp/log package.
func StartAllowingMissingConfig(workingDir string, logLevel int) (*UdpAgent, error) {
	if workingDir == "" {
		return nil, fmt.Errorf("working directory is required")
	}
	missingConfig := !configTomlExists(workingDir)
	instance := &UdpAgent{}
	instance.SetAllowMissingConfig(true)
	if err := instance.Start(workingDir, logLevel); err != nil {
		// Start installs the agent logger as the global logger before it can
		// fail; close it so a failed bootstrap does not leak the log file.
		if instance.log != nil {
			instance.log.Close()
		}
		return nil, err
	}
	if missingConfig && instance.log != nil {
		instance.log.SetLogLevel(logLevel)
	}
	return instance, nil
}

func agentCipherScheme(a *UdpAgent) int {
	if a == nil || a.config == nil {
		return common.CIPHER_SCHEME_CURVE
	}
	// GetCipherScheme reads under keyMu; the config watcher (updateBaseConfig ->
	// SetCipherScheme) writes DefaultCipherScheme under the same lock, so a bare
	// field read here would race a config reload.
	return a.config.GetCipherScheme()
}

func invalidRegistration(msg string) RegistrationResult {
	return RegistrationResult{
		ErrCode: common.ErrInvalidInput.ErrorCode(),
		ErrMsg:  msg,
	}
}

// InstallRegistrationKey installs privateKey on an idle agent. An empty
// privateKey generates a new key for cipherType (0 Curve25519, 1 SM2).
// When the key already matches, a different cipherType is still applied.
func InstallRegistrationKey(a *UdpAgent, privateKey string, cipherType int) error {
	if a == nil {
		return fmt.Errorf("agent is not started")
	}
	if !validRegistrationCipherType(cipherType) {
		return fmt.Errorf("cipherType must be 0 (Curve25519) or 1 (SM2)")
	}
	if privateKey != "" && AgentHoldsRegistrationKey(a, privateKey, cipherType) {
		return nil
	}
	var priv []byte
	if privateKey == "" {
		ecc := core.ECC_CURVE25519
		if core.EccTypeEnum(cipherType) == core.ECC_SM2 {
			ecc = core.ECC_SM2
		}
		priv = core.NewECDH(ecc).PrivateKey()
	} else {
		decoded, err := base64.StdEncoding.DecodeString(privateKey)
		if err != nil {
			return fmt.Errorf("private key is not valid base64")
		}
		priv = decoded
	}
	return a.ReinitWithKey(priv, cipherSchemeFor(cipherType))
}

func applyRegistrationUser(a *UdpAgent, email string, deviceId string, orgId string, userData string) error {
	data := map[string]any{}
	if userData != "" {
		if err := json.Unmarshal([]byte(userData), &data); err != nil {
			return fmt.Errorf("userData is not valid JSON")
		}
	}
	if email != "" {
		data["email"] = email
	}
	a.SetDeviceId(deviceId)
	a.SetKnockUser(email, orgId, data)
	return nil
}

func registrationTarget(a *UdpAgent, aspId string, resId string, cluster string) (*KnockTarget, error) {
	resource := &KnockResource{
		AuthServiceId: aspId,
		ResourceId:    resId,
		Cluster:       cluster,
	}
	sc, err := a.FindServerClusterFromResource(resource)
	if err != nil {
		return nil, err
	}
	if sc == nil {
		return nil, common.ErrKnockServerNotFound
	}
	return &KnockTarget{
		KnockResource: *resource,
		ServerPeer:    sc.RepresentativePeer(),
		ServerCluster: sc,
	}, nil
}

// prepareRegistration selects an agent that can send the OTP or register call.
// A running agent is used only when its key and cipher scheme already match.
// ReinitWithKey is not called on that agent. Any other case starts a
// short-lived agent, which the caller must Stop, and which must not replace
// the caller's saved instance.
func prepareRegistration(current *UdpAgent, workingDir string, logLevel int, privateKey string, cipherType int, email string, deviceId string, orgId string, userData string, aspId string, resId string, cluster string, generateKey bool) (RegistrationResult, *UdpAgent, *KnockTarget, bool) {
	if email == "" || aspId == "" || resId == "" || cluster == "" {
		return invalidRegistration("email, aspId, resId, and cluster are required"), nil, nil, false
	}
	if !validRegistrationCipherType(cipherType) {
		return invalidRegistration("cipherType must be 0 (Curve25519) or 1 (SM2)"), nil, nil, false
	}

	scheme := cipherSchemeFor(cipherType)
	var instance *UdpAgent
	owned := false
	if current != nil && current.IsRunning() {
		switch {
		case privateKey == "" && generateKey:
			return invalidRegistration("close the running agent before generating a registration key"), nil, nil, false
		case privateKey == "" && current.PrivateKeyBase64() == "":
			return invalidRegistration("privateKey is required"), nil, nil, false
		case agentCipherScheme(current) != scheme:
			return invalidRegistration("close the running agent before changing the cipher scheme"), nil, nil, false
		// Compare by derived public key, not the raw config string: an agent
		// started from a sealed key holds the sealed blob there, which never
		// equals the plaintext key the caller passes.
		case privateKey != "" && !AgentHoldsRegistrationKey(current, privateKey, cipherType):
			return invalidRegistration("close the running agent before registering a different key"), nil, nil, false
		default:
			instance = current
		}
	} else if privateKey == "" && !generateKey {
		return invalidRegistration("privateKey is required"), nil, nil, false
	} else {
		started, err := StartAllowingMissingConfig(workingDir, logLevel)
		if err != nil {
			return RegistrationResult{
				ErrCode: registrationErrorCode(err),
				ErrMsg:  err.Error(),
			}, nil, nil, false
		}
		instance = started
		owned = true
		if err := InstallRegistrationKey(instance, privateKey, cipherType); err != nil {
			instance.Stop()
			return RegistrationResult{
				ErrCode: registrationErrorCode(err),
				ErrMsg:  err.Error(),
			}, nil, nil, false
		}
	}

	if err := applyRegistrationUser(instance, email, deviceId, orgId, userData); err != nil {
		if owned {
			instance.Stop()
		}
		return invalidRegistration(err.Error()), nil, nil, false
	}
	result := RegistrationResult{
		PublicKey: instance.PublicKeyBase64ByCipherScheme(),
	}
	target, err := registrationTarget(instance, aspId, resId, cluster)
	if err != nil {
		if owned {
			instance.Stop()
		}
		result.ErrCode = registrationErrorCode(err)
		result.ErrMsg = err.Error()
		return result, nil, nil, false
	}
	return result, instance, target, owned
}

func finishOwnedAgent(instance *UdpAgent, owned bool) {
	if owned && instance != nil {
		instance.Stop()
	}
}

// knockIdentity is a value snapshot of the agent fields that
// applyRegistrationUser overwrites, so the register flow can put a reused live
// agent back the way it found it.
type knockIdentity struct {
	hadUser  bool
	user     KnockUser
	deviceId string
}

// snapshotKnockIdentity copies a's knock user and device id under
// knockUserMutex. It takes a value copy, not the *KnockUser pointer, because
// SetKnockUser overwrites that struct's fields in place — a captured pointer
// would just observe the overwrite.
func snapshotKnockIdentity(a *UdpAgent) knockIdentity {
	a.knockUserMutex.Lock()
	defer a.knockUserMutex.Unlock()
	snap := knockIdentity{deviceId: a.deviceId}
	if a.knockUser != nil {
		snap.hadUser = true
		snap.user = *a.knockUser
	}
	return snap
}

// restoreKnockIdentity writes a snapshot back under knockUserMutex, matching the
// lock the knock-sending path takes to read these fields.
func restoreKnockIdentity(a *UdpAgent, snap knockIdentity) {
	a.knockUserMutex.Lock()
	defer a.knockUserMutex.Unlock()
	a.deviceId = snap.deviceId
	if snap.hadUser {
		if a.knockUser == nil {
			a.knockUser = &KnockUser{}
		}
		*a.knockUser = snap.user
	}
}

// waitForOtpSend blocks until the agent has transmitted the pending OTP
// datagram (its sent-byte counter advances past baseline) or timeout elapses.
//
// RequestOtp only enqueues the packet; sendMessageRoutine transmits it
// asynchronously via SendPacket, which bumps stats.totalSendBytes once the
// datagram is written to the socket. NHP-OTP is fire-and-forget (the server
// sends no ack, unlike NHP-REG), so a sent-byte advance is the only completion
// signal available agent-side. The caller MUST NOT Stop the owned agent before
// this returns true, or Stop() closes the device send queue underneath the
// in-flight packet and it is dropped (or, without the core recover guard,
// panics). Once the counter advances the UDP write has returned, so a later
// Stop cannot un-send the datagram. An upstream RequestOtp that blocks until
// the packet is sent would make this return immediately.
func waitForOtpSend(a *UdpAgent, baseline uint64, timeout time.Duration) bool {
	deadline := time.Now().Add(timeout)
	for {
		if atomic.LoadUint64(&a.stats.totalSendBytes) > baseline {
			return true
		}
		if !time.Now().Before(deadline) {
			return false
		}
		time.Sleep(10 * time.Millisecond)
	}
}

// RequestRegistrationOtp sends NHP-OTP for this agent key. An empty privateKey
// generates a key only when no agent is running. A running agent is never re-keyed.
// When a key is generated it is not returned in the result; the caller retrieves
// it once via TakeGeneratedKey and writes it straight to secure storage.
func RequestRegistrationOtp(current *UdpAgent, workingDir string, logLevel int, privateKey string, cipherType int, email string, deviceId string, orgId string, userData string, aspId string, resId string, cluster string) RegistrationResult {
	// Clear any key left unread by an earlier request before this one can
	// generate its own, so a stale secret is never held across requests.
	stashGeneratedKey("")
	// When this call reuses the caller's running agent, prepareRegistration ->
	// applyRegistrationUser overwrites that agent's knock identity. Snapshot it
	// now and restore it on return so the live agent keeps knocking as before.
	// (A knock racing this call still sees the temporary identity for the
	// duration — acceptable for the serial register-then-knock SDK flow; the
	// lock is not held across the network wait, so knocks are never stalled.)
	if current != nil && current.IsRunning() {
		snap := snapshotKnockIdentity(current)
		defer restoreKnockIdentity(current, snap)
	}
	result, instance, target, owned := prepareRegistration(
		current, workingDir, logLevel, privateKey, cipherType, email, deviceId, orgId, userData, aspId, resId, cluster, true,
	)
	defer finishOwnedAgent(instance, owned)
	if target == nil {
		return result
	}
	sentBaseline := atomic.LoadUint64(&instance.stats.totalSendBytes)
	if err := instance.RequestOtp(target); err != nil {
		result.ErrCode = registrationErrorCode(err)
		result.ErrMsg = err.Error()
		return result
	}
	// Only an owned throwaway agent is Stopped right after this, so only it can
	// drop the fire-and-forget OTP during shutdown — wait for the packet to
	// leave before finishOwnedAgent stops it. The wait is also only meaningful
	// for an owned agent: totalSendBytes is a shared counter, so on a reused
	// running agent a concurrent knock or keep-alive would move it and the wait
	// could not attribute the bump to this OTP. A reused agent is not stopped
	// here, so skipping the wait for it cannot drop the datagram.
	if owned && !waitForOtpSend(instance, sentBaseline, 3*time.Second) {
		result.ErrCode = registrationErrorCode(common.ErrPacketToMessageRoutineStopped)
		result.ErrMsg = "otp request was not transmitted; check the server address and network"
		return result
	}
	// A key was generated here only when the caller passed none; hand it to
	// TakeGeneratedKey so it can be stored, but never place it in the result.
	if privateKey == "" {
		stashGeneratedKey(instance.PrivateKeyBase64())
	}
	result.PublicKey = instance.PublicKeyBase64ByCipherScheme()
	result.ErrCode = common.ErrSuccess.ErrorCode()
	return result
}

// RegisterDevice submits the one-time password for the key from
// RequestRegistrationOtp. privateKey must be that key. An empty privateKey is
// accepted only when current is running and already holds one. A running agent
// is never re-keyed.
func RegisterDevice(current *UdpAgent, workingDir string, logLevel int, privateKey string, cipherType int, email string, deviceId string, orgId string, userData string, aspId string, resId string, cluster string, otp string) RegistrationResult {
	if otp == "" {
		return invalidRegistration("otp is required")
	}
	// Same as RequestRegistrationOtp: if we reuse the caller's running agent,
	// restore its knock identity on return so registration does not silently
	// change what the live agent knocks as.
	if current != nil && current.IsRunning() {
		snap := snapshotKnockIdentity(current)
		defer restoreKnockIdentity(current, snap)
	}
	result, instance, target, owned := prepareRegistration(
		current, workingDir, logLevel, privateKey, cipherType, email, deviceId, orgId, userData, aspId, resId, cluster, false,
	)
	defer finishOwnedAgent(instance, owned)
	if target == nil {
		return result
	}
	ack, err := instance.RegisterPublicKey(otp, target)
	if ack != nil {
		result.ErrCode = ack.ErrCode
		result.ErrMsg = ack.ErrMsg
		result.AuthServiceId = ack.AuthServiceId
		result.ExpiresAt = ack.ExpiresAt
	}
	if err != nil && result.ErrCode == "" {
		result.ErrCode = registrationErrorCode(err)
		result.ErrMsg = err.Error()
	}
	if result.ErrCode == "" {
		result.ErrCode = common.ErrSuccess.ErrorCode()
	}
	// RegisterDevice never generates a key (prepareRegistration rejects an empty
	// privateKey here), so there is nothing to surrender and nothing to return.
	result.PublicKey = instance.PublicKeyBase64ByCipherScheme()
	return result
}
