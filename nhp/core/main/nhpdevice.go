// The device registry is shared by every thread of the host process.
// Unsynchronized Go map access from two threads is a fatal runtime error
// that no recover can catch, so every access goes through deviceMu.
//
// Handles come from a counter rather than from the device's address: an
// address can be reused for a new device once a closed one is garbage
// collected, and a stale handle would then silently reach that new device
// (and its keys) instead of failing with ERR_NHP_DEVICE_NOT_INITIALIZED.
//
// Closing a device only unregisters it. A call that already looked the
// device up runs to completion on it; nothing a C caller holds is freed
// by close, so that is safe.
type registeredDevice struct {
	device *core.Device
	key    string
}

var (
	deviceMu   sync.RWMutex
	nextHandle uintptr
	devices    = make(map[string]uintptr) // private key (base64) -> handle
	handles    = make(map[uintptr]registeredDevice)
)

// No Go panic may cross the cgo boundary: it aborts the whole host process
// (a C/C++ or other-language application), and the input that triggers it
// can be a single malformed packet from an unauthenticated peer. Every
// exported function that returns a result therefore defers
// recoverToResult, and validates every length and pointer it receives
// before using it.

// recoverToResult turns a panic in an exported function into
// ERR_NHP_SDK_RUNTIME_PANIC in its result. It must be deferred directly,
// and the exported function must use a named result (resultPtr), or a
// recovered panic would hand the C caller a NULL result instead.
func recoverToResult(errCode *C.int, errMsg **C.char) {
	if r := recover(); r != nil {
		setError(errCode, errMsg, C.ERR_NHP_SDK_RUNTIME_PANIC, fmt.Sprintf("nhp sdk internal error: %v", r))
	}
}

// setError stores an error code and message in a result, replacing any
// message already there.
func setError(errCode *C.int, errMsg **C.char, code C.int, msg string) {
	*errCode = code
	if *errMsg != nil {
		C.free(unsafe.Pointer(*errMsg))
	}
	*errMsg = C.CString(msg)
}

// errorCode maps an error to the code reported to the C caller: the NHP
// error number for a *core.Error (possibly wrapped), -1 for anything else.
// RecvPrecheck, for one, returns plain errors for malformed packets, which
// the former single-value type assertion turned into a panic. A panic that
// the core recovers itself comes back as core.ErrRuntimePanic, whose
// number is the same ERR_NHP_SDK_RUNTIME_PANIC that recoverToResult uses.
func errorCode(err error) C.int {
	var nhpErr *core.Error
	if errors.As(err, &nhpErr) && nhpErr != nil {
		return C.int(nhpErr.ErrorNumber())
	}
	return -1
}

// errorMessage is the errMsg reported to the C caller for err. A panic the
// core recovered itself comes back as core.ErrRuntimePanic carrying the
// full panic value and stack trace; on the decrypt path an unauthenticated
// packet can trigger that, so only the short description is reported.
func errorMessage(err error) string {
	if errors.Is(err, core.ErrRuntimePanic) {
		return "runtime panic encountered"
	}
	return err.Error()
}

// cBytes copies a caller-supplied (pointer, length) buffer into Go memory
// after checking it: the length must not be negative or above max (max < 0
// means no upper bound), and a NULL pointer is only accepted with length 0.
func cBytes(name string, ptr *C.uchar, length C.int, max int) ([]byte, error) {
	switch {
	case length < 0:
		return nil, fmt.Errorf("%s: negative length %d", name, int(length))
	case max >= 0 && int(length) > max:
		return nil, fmt.Errorf("%s: length %d exceeds %d", name, int(length), max)
	case length > 0 && ptr == nil:
		return nil, fmt.Errorf("%s: NULL buffer with length %d", name, int(length))
	case length == 0:
		return []byte{}, nil
	}
	return C.GoBytes(unsafe.Pointer(ptr), length), nil
}

func lookupDevice(handle uintptr) (*core.Device, bool) {
	deviceMu.RLock()
	defer deviceMu.RUnlock()
	reg, found := handles[handle]
	return reg.device, found
}

// Release the memory of the string buffer generated by NHPSDK.
//
//export nhp_free_cstring
func nhp_free_cstring(ptr *C.char) {
	C.free(unsafe.Pointer(ptr))
}

// Release the memory buffer of the nhpresult structure generated by NHPSDK.
//
//export nhp_free_NhpResult
func nhp_free_NhpResult(ptr *C.NhpResult) {
	if ptr == nil {
		return
	}
	C.free(unsafe.Pointer(ptr.errMsg))
	C.free(unsafe.Pointer(ptr))
}

// Release the memory buffer of the NhpEncryptResult structure generated by NHPSDK.
//
//export nhp_free_NhpEncryptResult
func nhp_free_NhpEncryptResult(ptr *C.NhpEncryptResult) {
	if ptr == nil {
		return
	}
	C.free(unsafe.Pointer(ptr.errMsg))
	C.free(unsafe.Pointer(ptr.packet))
	C.free(unsafe.Pointer(ptr))
}

// Release the memory buffer of the NhpDecryptResult structure generated by NHPSDK.
//
//export nhp_free_NhpDecryptResult
func nhp_free_NhpDecryptResult(ptr *C.NhpDecryptResult) {
	if ptr == nil {
		return
	}
	C.free(unsafe.Pointer(ptr.errMsg))
	C.free(unsafe.Pointer(ptr.msgId))
	C.free(unsafe.Pointer(ptr.data))
	C.free(unsafe.Pointer(ptr))
}

// Initialize the nhp_device instance
//
// Input:
// deviceType: The NHP component represented by this device: 1: nhp-agent, 2: nhp-server, 3: nhp-ac
// privateKeyBase64: Base64 encoding of the private key
//
// Return:
// NhpResult pointer:
// errCode 0: nhp device instance initialization successful
// Non-zero: nhp device instance initialization failed, errMsg: Error description
//
// Caller: Release the returned data after the call is completed, refer to the nhp_free_NhpResult function
//
//export nhp_device_init
func nhp_device_init(deviceType C.int, privateKeyBase64 string) (resultPtr *C.NhpResult) {
	resultPtr = (*C.NhpResult)(C.malloc(C.sizeof_NhpResult))
	C.memset(unsafe.Pointer(resultPtr), 0, C.sizeof_NhpResult)
	defer recoverToResult(&resultPtr.errCode, &resultPtr.errMsg)

	deviceMu.Lock()
	defer deviceMu.Unlock()

	// A string parameter of an exported function points into the C
	// caller's memory and is only valid during this call; the registry
	// keeps it, so it needs a Go-owned copy.
	key := strings.Clone(privateKeyBase64)

	if _, found := devices[key]; found {
		setError(&resultPtr.errCode, &resultPtr.errMsg, C.ERR_NHP_DEVICE_ALREADY_CREATED, "nhp device already created with the given key")
		return resultPtr
	}

	privateKey, err := base64.StdEncoding.DecodeString(key)
	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, C.ERR_NHP_CREATE_DEVICE_FAILED, "key invalid")
		return resultPtr
	}

	device := core.NewDevice(int(deviceType), privateKey, nil)
	if device == nil {
		// NewDevice returns nil for a key it cannot use. Registering it
		// would hand out a handle for a nil device and report success.
		setError(&resultPtr.errCode, &resultPtr.errMsg, C.ERR_NHP_CREATE_DEVICE_FAILED, "key invalid")
		return resultPtr
	}

	nextHandle++ // starts at 1, so 0 is never a valid handle
	devices[key] = nextHandle
	handles[nextHandle] = registeredDevice{device: device, key: key}
	resultPtr.handle = C.size_t(nextHandle)
	return resultPtr
}

// Close nhp_device
// Input:
// handle: NHP device handle
//
//export nhp_device_close
func nhp_device_close(handle uintptr) {
	deviceMu.Lock()
	defer deviceMu.Unlock()

	if reg, found := handles[handle]; found {
		delete(handles, handle)
		delete(devices, reg.key)
	}
}

// Perform NHP noise encryption on the payload data (plaintext message) and generate an NHP encrypted message
//
// Input:
// handle: NHP device handle
// msgType: NHP message type
// peerPbk: Peer public key
// peerPbkLen: Length of peer public key
// data: Plaintext payload
// dataLen: Length of plaintext payload
// params: Encryption parameters, refer to the NhpEncryptParams structure
//
// Return:
// Pointer to NhpEncryptResult, refer to the NhpEncryptResult structure
//
// Caller: After calling, release the returned data, refer to the nhp_free_NhpEncryptResult function
//
//export nhp_device_encrypt_data
func nhp_device_encrypt_data(handle uintptr, msgType C.int, peerPbk *C.uchar, peerPbkLen C.int, data *C.uchar, dataLen C.int, params C.NhpEncryptParams) (resultPtr *C.NhpEncryptResult) {
	resultPtr = (*C.NhpEncryptResult)(C.malloc(C.sizeof_NhpEncryptResult))
	C.memset(unsafe.Pointer(resultPtr), 0, C.sizeof_NhpEncryptResult)
	defer recoverToResult(&resultPtr.errCode, &resultPtr.errMsg)

	device, found := lookupDevice(handle)
	if !found {
		setError(&resultPtr.errCode, &resultPtr.errMsg, C.ERR_NHP_DEVICE_NOT_INITIALIZED, "nhp device not initialized")
		return resultPtr
	}

	peerPk, err := cBytes("peerPbk", peerPbk, peerPbkLen, core.PublicKeySizeEx)
	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, -1, err.Error())
		return resultPtr
	}
	// The plaintext may be compressed into a packet, so it is bounded by
	// the largest body the core accepts, not by the packet size.
	message, err := cBytes("data", data, dataLen, core.MaxDecompressedBodySize)
	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, -1, err.Error())
		return resultPtr
	}

	md := &core.MsgData{
		HeaderType:     int(msgType),
		CipherScheme:   int(params.cipherScheme),
		PeerPk:         peerPk,
		Message:        message,
		Compress:       params.compress != 0,
		TransactionId:  uint64(params.assignTransactionId),
		ExternalCookie: (*[core.CookieSize]byte)(unsafe.Pointer(&params.cookie)),
	}

	mad, err := device.MsgToPacket(md)
	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, errorCode(err), errorMessage(err))
	} else {
		resultPtr.transactionId = C.ulonglong(mad.TransactionId)
		resultPtr.packet = (*C.uchar)(C.CBytes(mad.BasePacket.Content))
		resultPtr.packetLen = C.int(len(mad.BasePacket.Content))
	}

	return resultPtr
}

// Perform NHP noise encryption on the payload data (plaintext message) and generate an NHP packet
//
// Input:
// handle: NHP device handle
// packet: NHP encrypted packet to be parsed
// packetLen: Length of the NHP encrypted packet
//
// Returns:
// Pointer to NhpDecryptResult, refer to the NhpDecryptResult structure
//
// Caller: Release the returned data after the call is complete, refer to the nhp_free_NhpDecryptResult function
//
//export nhp_device_decrypt_packet
func nhp_device_decrypt_packet(handle uintptr, packet *C.uchar, packetLen C.int, context C.NhpConnContext) (resultPtr *C.NhpDecryptResult) {
	resultPtr = (*C.NhpDecryptResult)(C.malloc(C.sizeof_NhpDecryptResult))
	C.memset(unsafe.Pointer(resultPtr), 0, C.sizeof_NhpDecryptResult)
	defer recoverToResult(&resultPtr.errCode, &resultPtr.errMsg)

	device, found := lookupDevice(handle)
	if !found {
		setError(&resultPtr.errCode, &resultPtr.errMsg, C.ERR_NHP_DEVICE_NOT_INITIALIZED, "nhp device not initialized")
		return resultPtr
	}

	// The packet comes from the network, before the peer is authenticated.
	// Bound it by what a receive buffer can hold and by the smallest NHP
	// header (curve.HeaderSize, i.e. Packet.MinimalLength), so every
	// length problem reports ERR_NHP_INCORRECT_PACKET_SIZE. RecvPrecheck
	// (inside PacketToMsg) still checks the scheme's full header size.
	content, err := cBytes("packet", packet, packetLen, core.PacketBufferSize)
	if err == nil && len(content) < curve.HeaderSize {
		err = fmt.Errorf("packet: length %d is shorter than an NHP header (%d)", len(content), curve.HeaderSize)
	}
	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, C.ERR_NHP_INCORRECT_PACKET_SIZE, err.Error())
		return resultPtr
	}

	var cookieStore *core.CookieStore
	if context.cookieStore != nil {
		cookieStore = (*core.CookieStore)(unsafe.Pointer(context.cookieStore))
	}

	var lastPeerSendTime *int64
	if context.lastPeerSendTime != nil {
		lastPeerSendTime = (*int64)(unsafe.Pointer(context.lastPeerSendTime))
	}

	var peerPbk *[core.PublicKeySizeEx]byte
	if context.peerPbk != nil {
		peerPbk = (*[core.PublicKeySizeEx]byte)(unsafe.Pointer(context.peerPbk))
	}

	pd := &core.PacketData{
		BasePacket:             &core.Packet{Content: content},
		ConnLastRemoteSendTime: lastPeerSendTime,
		ConnCookieStore:        cookieStore,
		ConnPeerPublicKey:      peerPbk,
	}

	ppd, err := device.PacketToMsg(pd)

	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, errorCode(err), errorMessage(err))
	} else {
		resultPtr.msgType = C.int(ppd.HeaderType)
		if ppd.HeaderType != core.NHP_KPL {
			resultPtr.msgTransactionId = C.ulonglong(ppd.SenderTrxId)
			resultPtr.msgId = (*C.uchar)(C.CBytes(ppd.SenderIdentity))
			resultPtr.msgIdLen = C.int(len(ppd.SenderIdentity))
			resultPtr.data = (*C.uchar)(C.CBytes(ppd.BodyMessage))
			resultPtr.dataLen = C.int(len(ppd.BodyMessage))
		}
	}

	return resultPtr
}

// Set overload mode for nhp device
//
// Input:
// handle: Handle to the NHP device
// overload: Boolean indicating whether to enable overload mode
//
// Return:
// Pointer to NhpResult, refer to NhpResult structure
//
// Caller: Release the returned data after the call, refer to nhp_free_NhpResult function
//
//export nhp_device_set_overload
func nhp_device_set_overload(handle uintptr, overload bool) (resultPtr *C.NhpResult) {
	resultPtr = (*C.NhpResult)(C.malloc(C.sizeof_NhpResult))
	C.memset(unsafe.Pointer(resultPtr), 0, C.sizeof_NhpResult)
	defer recoverToResult(&resultPtr.errCode, &resultPtr.errMsg)

	device, found := lookupDevice(handle)
	if !found {
		setError(&resultPtr.errCode, &resultPtr.errMsg, C.ERR_NHP_DEVICE_NOT_INITIALIZED, "nhp device not initialized")
		return resultPtr
	}

	device.SetOverload(overload)
	return resultPtr
}

// Perform SM4 AEAD encryption
//
// Input:
// key: Key buffer
// keyLen: Key length (the first 16 bytes are used)
// nonce: Counter value buffer
// nonceLen: Counter value length (must be 12 bytes)
// plain: Plain text data
// plainLen: Plain text length
// additionalData: Additional authenticated data
// additionalDataLen: Length of additional authenticated data
//
// Return:
// Pointer to NhpEncryptResult, with the ciphertext represented by packet and packetLen.
// errCode is 1 for any failure, including invalid arguments.
//
// Caller: After the function call, release the returned data, refer to the nhp_free_NhpEncryptResult function
//
//export nhp_sm4_aead_encrypt
func nhp_sm4_aead_encrypt(key *C.uchar, keyLen C.int, nonce *C.uchar, nonceLen C.int, plain *C.uchar, plainLen C.int, additionalData *C.uchar, additionalDataLen C.int) (resultPtr *C.NhpEncryptResult) {
	resultPtr = (*C.NhpEncryptResult)(C.malloc(C.sizeof_NhpEncryptResult))
	C.memset(unsafe.Pointer(resultPtr), 0, C.sizeof_NhpEncryptResult)
	defer recoverToResult(&resultPtr.errCode, &resultPtr.errMsg)

	aead, nonceBytes, err := sm4AeadInputs(key, keyLen, nonce, nonceLen)
	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, 1, err.Error())
		return resultPtr
	}
	plainBytes, err := cBytes("plain", plain, plainLen, -1)
	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, 1, err.Error())
		return resultPtr
	}
	aad, err := cBytes("additionalData", additionalData, additionalDataLen, -1)
	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, 1, err.Error())
		return resultPtr
	}

	buf := make([]byte, 0, len(plainBytes)+aead.Overhead())
	sealed := aead.Seal(buf, nonceBytes, plainBytes, aad)

	resultPtr.packet = (*C.uchar)(C.CBytes(sealed))
	resultPtr.packetLen = C.int(len(sealed))
	return resultPtr
}

// Perform SM4 AEAD decryption
//
// Input:
// key: Key buffer
// keyLen: Key length (the first 16 bytes)
// nonce: Counter value buffer (must be the same as the counter value during encryption)
// nonceLen: Counter value length (must be 12 bytes)
// cipher: Ciphertext data
// cipherLen: Ciphertext length
// additionalData: Additional verification data
// additionalDataLen: Length of additional verification data
//
// Return:
// Pointer to NhpDecryptResult, plaintext is represented by data and dataLen.
// errCode is 1 for any failure, including invalid arguments.
//
// Caller: Release the returned data after the call is complete, refer to the nhp_free_NhpEncryptResult function
//
//export nhp_sm4_aead_decrypt
func nhp_sm4_aead_decrypt(key *C.uchar, keyLen C.int, nonce *C.uchar, nonceLen C.int, cipher *C.uchar, cipherLen C.int, additionalData *C.uchar, additionalDataLen C.int) (resultPtr *C.NhpDecryptResult) {
	resultPtr = (*C.NhpDecryptResult)(C.malloc(C.sizeof_NhpDecryptResult))
	C.memset(unsafe.Pointer(resultPtr), 0, C.sizeof_NhpDecryptResult)
	defer recoverToResult(&resultPtr.errCode, &resultPtr.errMsg)

	aead, nonceBytes, err := sm4AeadInputs(key, keyLen, nonce, nonceLen)
	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, 1, err.Error())
		return resultPtr
	}
	cipherBytes, err := cBytes("cipher", cipher, cipherLen, -1)
	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, 1, err.Error())
		return resultPtr
	}
	aad, err := cBytes("additionalData", additionalData, additionalDataLen, -1)
	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, 1, err.Error())
		return resultPtr
	}

	plain, err := aead.Open(make([]byte, 0, len(cipherBytes)), nonceBytes, cipherBytes, aad)
	if err != nil {
		setError(&resultPtr.errCode, &resultPtr.errMsg, 1, fmt.Sprintf("GCM decryption failed: %s", err))
		return resultPtr
	}

	resultPtr.data = (*C.uchar)(C.CBytes(plain))
	resultPtr.dataLen = C.int(len(plain))
	return resultPtr
}

// sm4KeySize is the number of key bytes SM4-GCM uses (core.AeadFromKey
// takes the first 16 bytes of the symmetric key).
const sm4KeySize = 16

// sm4AeadInputs validates the key and nonce passed to the SM4 helpers and
// builds the AEAD. A key shorter than 16 bytes is refused instead of being
// silently zero-padded, and a nonce of the wrong size is refused instead of
// making Seal/Open panic.
func sm4AeadInputs(key *C.uchar, keyLen C.int, nonce *C.uchar, nonceLen C.int) (stdcipher.AEAD, []byte, error) {
	if keyLen < sm4KeySize || key == nil {
		return nil, nil, fmt.Errorf("key: need at least %d bytes, got %d", sm4KeySize, int(keyLen))
	}
	var aeadKey [core.SymmetricKeySize]byte
	copy(aeadKey[:], C.GoBytes(unsafe.Pointer(key), sm4KeySize))

	aead, err := core.AeadFromKey(core.GCM_SM4, &aeadKey)
	if err != nil {
		return nil, nil, fmt.Errorf("failed to create AEAD: %w", err)
	}
	if int(nonceLen) != aead.NonceSize() || nonce == nil {
		return nil, nil, fmt.Errorf("nonce: need %d bytes, got %d", aead.NonceSize(), int(nonceLen))
	}
	return aead, C.GoBytes(unsafe.Pointer(nonce), nonceLen), nil
}
